// Decides which AI engine serves a request:
//   1. The user's own key (BYOK): preferred provider first; never rate limited.
//   2. The platform's key from the environment, subject to a daily per-user quota.
//   3. The offline rule-based assistant, when neither is available.

import { decryptSecret } from "@/lib/crypto";
import { prisma } from "@/lib/db";
import { parseResumeData } from "@/lib/resume/schema";
import { runLocalTask } from "./local";
import { AiProviderError, PROVIDER_LABELS, PROVIDERS, complete, defaultModel, isProviderId, type ProviderId } from "./providers";
import { PARSE_PROMPT, SYSTEM_PROMPT, buildPrompt, parseOutput, parseResumeJson, type AiResult, type AiTask } from "./tasks";

export type EngineKind = "user" | "platform" | "local";

export interface EngineInfo {
  kind: EngineKind;
  provider?: ProviderId;
  model?: string;
  /** Human-readable description shown in the UI. */
  label: string;
  /** Extra context, e.g. why we fell back to the offline assistant. */
  notice?: string;
}

interface RemoteEngine {
  kind: "user" | "platform";
  provider: ProviderId;
  model: string;
  apiKey: string;
}

export function apiKeyAad(userId: string, provider: string): string {
  return `${userId}:${provider}`;
}

export function platformProvider(): { provider: ProviderId; apiKey: string } | null {
  const keyFor: Record<ProviderId, string | undefined> = {
    openrouter: process.env.OPENROUTER_API_KEY,
    anthropic: process.env.ANTHROPIC_API_KEY,
    openai: process.env.OPENAI_API_KEY,
    gemini: process.env.GEMINI_API_KEY,
  };
  const preferred = process.env.PLATFORM_AI_PROVIDER;
  const order = isProviderId(preferred) ? [preferred, ...PROVIDERS.filter((p) => p !== preferred)] : [...PROVIDERS];
  const provider = order.find((p) => keyFor[p]?.trim());
  return provider ? { provider, apiKey: keyFor[provider]!.trim() } : null;
}

export function platformDailyLimit(): number {
  const n = Number(process.env.PLATFORM_AI_DAILY_LIMIT);
  return Number.isFinite(n) && n >= 0 ? n : 25;
}

const today = () => new Date().toISOString().slice(0, 10);

export async function platformUsageToday(userId: string): Promise<number> {
  const usage = await prisma.aiUsage.findUnique({ where: { userId_day: { userId, day: today() } } });
  return usage?.count ?? 0;
}

/** Atomically consumes one unit of platform quota. Returns false when the limit is reached. */
async function consumePlatformQuota(userId: string): Promise<boolean> {
  const usage = await prisma.aiUsage.upsert({
    where: { userId_day: { userId, day: today() } },
    create: { userId, day: today(), count: 1 },
    update: { count: { increment: 1 } },
  });
  return usage.count <= platformDailyLimit();
}

async function userEngine(userId: string, preferred?: string | null): Promise<RemoteEngine | null> {
  const keys = await prisma.apiKey.findMany({ where: { userId } });
  if (!keys.length) return null;
  const ordered = [...keys].sort((a, b) => {
    const rank = (p: string) => (p === preferred ? -1 : PROVIDERS.indexOf(p as ProviderId));
    return rank(a.provider) - rank(b.provider);
  });
  for (const key of ordered) {
    if (!isProviderId(key.provider)) continue;
    try {
      const apiKey = decryptSecret(key.encryptedKey, apiKeyAad(userId, key.provider));
      return { kind: "user", provider: key.provider, model: key.model || defaultModel(key.provider), apiKey };
    } catch {
      // Undecryptable (e.g. ENCRYPTION_KEY rotated); try the next key.
    }
  }
  return null;
}

function describe(engine: RemoteEngine): EngineInfo {
  const who = engine.kind === "user" ? `your ${PROVIDER_LABELS[engine.provider]} key` : `platform AI (${PROVIDER_LABELS[engine.provider]})`;
  return { kind: engine.kind, provider: engine.provider, model: engine.model, label: `Generated with ${who}` };
}

const LOCAL_LABEL = "Generated by the offline writing assistant";

type Resolution = { engine: RemoteEngine; info: EngineInfo } | { engine: null; info: EngineInfo };

async function resolve(userId: string, preferredProvider?: string | null): Promise<Resolution> {
  const own = await userEngine(userId, preferredProvider);
  if (own) return { engine: own, info: describe(own) };

  const platform = platformProvider();
  if (platform) {
    if (await consumePlatformQuota(userId)) {
      const engine: RemoteEngine = { kind: "platform", ...platform, model: defaultModel(platform.provider) };
      return { engine, info: describe(engine) };
    }
    return {
      engine: null,
      info: {
        kind: "local",
        label: LOCAL_LABEL,
        notice: `You've used today's ${platformDailyLimit()} platform AI requests. Add your own API key in Settings for unlimited use.`,
      },
    };
  }
  return {
    engine: null,
    info: { kind: "local", label: LOCAL_LABEL, notice: "No AI provider is configured. Add an API key in Settings for AI-written content." },
  };
}

export class AiTaskError extends Error {
  constructor(
    message: string,
    readonly status: number,
  ) {
    super(message);
  }
}

/** Runs a writing task through the best available engine. */
export async function runAiTask(userId: string, task: AiTask, preferredProvider?: string | null): Promise<{ result: AiResult; engine: EngineInfo }> {
  const resume = task.type === "summary" || task.type === "tailor" ? parseResumeData(task.resume) : undefined;
  const { engine, info } = await resolve(userId, preferredProvider);
  if (!engine) return { result: runLocalTask(task), engine: info };

  try {
    const text = await complete({ ...engine, system: SYSTEM_PROMPT, prompt: buildPrompt(task, resume) });
    return { result: parseOutput(task, text), engine: info };
  } catch (err) {
    if (engine.kind === "user") {
      // Don't silently spend platform credits when the user's key fails; tell them.
      const message = err instanceof AiProviderError ? err.message : "The AI response could not be understood. Please try again.";
      throw new AiTaskError(`${message} Check your key in Settings.`, err instanceof AiProviderError && err.status === 401 ? 400 : 502);
    }
    console.error("[ai] platform provider failed, using offline assistant:", err instanceof Error ? err.message : err);
    return {
      result: runLocalTask(task),
      engine: { kind: "local", label: LOCAL_LABEL, notice: "The platform AI service is unavailable right now, so the offline assistant was used." },
    };
  }
}

/** Uses AI (if available) to structure raw resume text. Returns null when no AI engine can be used. */
export async function parseResumeWithAi(userId: string, text: string, preferredProvider?: string | null) {
  const { engine, info } = await resolve(userId, preferredProvider);
  if (!engine) return null;
  try {
    const output = await complete({ ...engine, system: SYSTEM_PROMPT, prompt: PARSE_PROMPT(text), maxTokens: 8000 });
    return { data: parseResumeJson(output), engine: info };
  } catch (err) {
    console.error("[ai] resume parsing failed, falling back to heuristic parser:", err instanceof Error ? err.message : err);
    return null;
  }
}

/** Sends a tiny request to verify that a key works. */
export async function testProviderKey(provider: ProviderId, apiKey: string, model?: string | null): Promise<void> {
  await complete({
    provider,
    apiKey,
    model: model || defaultModel(provider),
    system: "Reply with the single word OK.",
    prompt: "Say OK.",
    maxTokens: 16,
  });
}
